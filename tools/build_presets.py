#!/usr/bin/python3
"""Generate the shipped presets from the catalogue's own risk ratings.

Hand-maintained preset files drift away from the catalogue the moment a flag's
risk rating changes. Deriving them means "recommended" is *by definition* every
flag rated safe, and stays that way.

    python3 tools/build_presets.py            # rebuild the derived presets
    python3 tools/build_presets.py --stock    # also capture this machine as `stock`

The --stock pass is a stand-in for the full capture in BUILD_PLAN §5.2: it reads
the live state and records what is already in effect. It does not yet produce the
findings report (duplicate keys, invalid keys, conflicts), which is why capture is
still listed as unbuilt in the app.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from hardeninggui import catalogue as catalogue_module  # noqa: E402
from hardeninggui import probe, tomlemit  # noqa: E402

OUT = ROOT / "data" / "presets"

#: Flags no derived preset should ever turn on by itself.
#: - editable flags need a value only the user knows
#: - one-way flags stay deliberate (§5.1), except in paranoid
def _skip(flag, catalogue, allow_one_way: bool) -> bool:
    section = catalogue.section(flag.section)
    if not section.implemented:
        return True
    if flag.editable:
        return True
    if flag.is_one_way_at(flag.value) and not allow_one_way:
        return True
    return False


def by_risk(catalogue, risks: set[str], allow_one_way: bool = False) -> dict[str, str]:
    return {
        flag.id: flag.value
        for flag in catalogue.flags.values()
        if flag.risk in risks and not _skip(flag, catalogue, allow_one_way)
    }


def emit(name: str, desc: str, values: dict[str, str], base: str = "", note: str = "") -> None:
    entries = [{"id": key, "value": values[key]} for key in sorted(values)]
    meta: dict[str, object] = {"name": name}
    if base:
        meta["base"] = base
    meta["desc"] = desc
    header = (
        f"{name} — generated by tools/build_presets.py from the catalogue's risk "
        f"ratings.\nDo not hand-edit: rerun the tool instead.\n"
    )
    if note:
        header += f"\n{note}\n"
    path = OUT / f"{name}.toml"
    path.write_text(tomlemit.dumps({"preset": meta, "set": entries}, header=header))
    print(f"{path.name:22} {len(entries):4} flags")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stock", action="store_true", help="capture this machine")
    args = parser.parse_args()

    catalogue = catalogue_module.load()
    OUT.mkdir(parents=True, exist_ok=True)

    safe = by_risk(catalogue, {"safe"})
    emit(
        "recommended",
        "Everything rated safe. Nothing here breaks snaps, Wi-Fi or the desktop.",
        safe,
    )

    # laptop: safe set, plus MAC privacy and screen lock, minus anything that
    # costs half the CPU or kills the radios you actually use on the move.
    laptop = dict(safe)
    for flag_id in ("nm_wifi_cloned_mac", "nm_ethernet_cloned_mac", "nm_stable_id",
                    "lock_enabled", "lock_delay", "idle_delay", "show_in_lock_screen"):
        if flag_id in catalogue.flags:
            laptop[flag_id] = catalogue.flags[flag_id].value
    for flag_id in ("nosmt_force", "mitigations", "svc_wpa_supplicant", "svc_bluetooth"):
        laptop.pop(flag_id, None)
    emit(
        "laptop",
        "Safe set plus MAC-address privacy and screen lock. Keeps Wi-Fi, "
        "Bluetooth and both CPU threads.",
        laptop,
    )

    # workstation: safe set, but leave the developer's tools alone.
    workstation = dict(safe)
    for flag_id in ("perf_event_paranoid", "ptrace_scope", "io_uring_disabled",
                    "unprivileged_bpf_disabled", "bpf_jit_harden", "debugfs_off",
                    "mod_kvm", "mod_kvm_intel", "mod_kvm_amd", "binfmt_misc_off"):
        workstation.pop(flag_id, None)
    emit(
        "workstation",
        "Safe set with the developer tooling left working: ptrace, perf, eBPF, "
        "debugfs, KVM and binfmt_misc all stay as they are.",
        workstation,
    )

    # server: safe set plus SSH and audit, minus the desktop sections.
    server = dict(safe)
    for flag in catalogue.flags.values():
        if flag.section in ("ssh", "auditd") and not _skip(flag, catalogue, False):
            server[flag.id] = flag.value
    for flag in catalogue.flags.values():
        if flag.section in ("desktop", "telemetry"):
            server.pop(flag.id, None)
    server["mitigations"] = "auto,nosmt"
    emit(
        "server",
        "Safe set plus full SSH hardening and audit rules, without the desktop "
        "sections. Mitigations include nosmt.",
        server,
    )

    # paranoid: everything, one-way flags included. Badge-heavy by design.
    paranoid = by_risk(
        catalogue, {"safe", "caution", "breaking", "one-way"}, allow_one_way=True
    )
    emit(
        "paranoid",
        "Everything on, including the irreversible flags. This WILL break snaps, "
        "Wi-Fi, Bluetooth, USB storage and virtualisation. Test in a VM snapshot "
        "before it goes anywhere near a machine you need.",
        paranoid,
        note=(
            "Includes one-way flags. Applying this is not reversible by deleting a "
            "file — read the review diff line by line first."
        ),
    )

    if args.stock:
        facts = probe.gather(catalogue)
        states = probe.all_states(catalogue, facts)
        captured = {
            flag_id: (state.on_disk or state.live or catalogue.flags[flag_id].value)
            for flag_id, state in states.items()
            if state.state.value in ("applied", "pending-reboot")
            and catalogue.flags[flag_id].value_is_allowed(
                state.on_disk or state.live or catalogue.flags[flag_id].value
            )
        }
        emit(
            "stock",
            "Captured from the reference machine — what it already had in effect.",
            captured,
            note=(
                "Read from the live system, not from its config files, so it "
                "records what was actually in effect rather than what someone "
                "meant to set. The full capture (§5.2) additionally reports "
                "duplicate keys, invalid keys and conflicts; this does not."
            ),
        )

    return 0


if __name__ == "__main__":
    sys.exit(main())
